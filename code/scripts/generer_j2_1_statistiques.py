#!/usr/bin/env python3
"""Generate reproducible SQLInspect J2.1 statistics and methodological report.
Python 3.10+; standard library only. Input CSV generated by generer_j2_1_csv.py.
Run from repository root; no Java source required for J2.1.
"""
import argparse
import collections
import csv
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path


def write_csv(path, fields, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def schema_counts(path):
    obj = json.loads(path.read_text(encoding='utf-8-sig'))
    tables = [t for db in obj.get('Databases', []) for schema in db.get('Schemas', []) for t in schema.get('Tables', [])]
    return len(tables), sum(len(t.get('Columns', [])) for t in tables)


def metrics(path):
    root = ET.parse(path).getroot()
    project = root.find('./JavaElement')
    if project is None:
        raise ValueError('Missing Java project metrics')
    return {x.get('name'): int(x.get('value')) for x in project.findall('./Metrics/Metric')}


def masked_sql(sql):
    # Remove placeholders, quoted literals and comments to avoid counting keywords in strings.
    sql = re.sub(r'\{\{.*?\}\}', ' ?', sql, flags=re.S)
    sql = re.sub(r"'(?:''|\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"", ' ?', sql)
    sql = re.sub(r'/\*.*?\*/|--[^\n]*', ' ', sql, flags=re.S)
    return sql


def complexity(sql, query_type):
    """Heuristic indicators, NOT a SQL parser or SQLInspect's native complexity metric."""
    s = masked_sql(sql)
    join_count = len(re.findall(r'\bJOIN\b', s, flags=re.I))
    subquery_count = len(re.findall(r'\(\s*SELECT\b', s, flags=re.I))
    group_by = bool(re.search(r'\bGROUP\s+BY\b', s, flags=re.I))
    having = bool(re.search(r'\bHAVING\b', s, flags=re.I))
    union = bool(re.search(r'\bUNION\b', s, flags=re.I))
    score = join_count + 2*subquery_count + int(group_by) + int(having) + int(union)
    level = 'unclassified' if query_type == 'UNRESOLVED' else ('high' if score >= 4 else 'moderate' if score >= 2 else 'low')
    return {'join_count': join_count, 'subquery_count': subquery_count, 'group_by': int(group_by), 'having': int(having), 'union': int(union), 'complexity_score': score, 'heuristic_complexity': level}


def main():
    p = argparse.ArgumentParser(description='Generate J2.1 CSV statistics and English methodological report')
    p.add_argument('--exports', type=Path, required=True)
    p.add_argument('--inventory', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    a = p.parse_args()
    required = [a.inventory, a.exports/'pandora-JavaMetrics.xml', a.exports/'pandora-schema.json', a.exports/'pandora-smells.xml']
    for path in required:
        if not path.is_file():
            p.error('Missing file: '+str(path))
    with a.inventory.open('r', encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f))
    need = {'query_id','file_path','start_line','sql_type','sql_text','taa_match','has_dynamic_fragments'}
    if rows and not need.issubset(rows[0]):
        p.error('Inventory CSV is missing expected columns: '+', '.join(sorted(need-set(rows[0]))))
    if not rows:
        p.error('Inventory is empty')
    ids = [r['query_id'] for r in rows]
    if len(set(ids)) != len(ids):
        p.error('Duplicate query_id in inventory')
    a.output.mkdir(parents=True, exist_ok=True)
    native = metrics(a.exports/'pandora-JavaMetrics.xml')
    tables, columns = schema_counts(a.exports/'pandora-schema.json')
    type_counts = collections.Counter(r['sql_type'] for r in rows)
    by_file = collections.defaultdict(list)
    hotspot_keys = set()
    dyn_count = 0
    taa_count = 0
    complexity_rows = []
    for row in rows:
        file = row['file_path']
        by_file[file].append(row)
        hotspot_keys.add((file.casefold(),row['start_line']))
        dyn_count += row['has_dynamic_fragments'].lower() == 'true'
        taa_count += row['taa_match'].lower() == 'true'
        c = complexity(row['sql_text'], row['sql_type'])
        complexity_rows.append({'query_id': row['query_id'], 'file_path': file, 'start_line': row['start_line'], 'sql_type': row['sql_type'], **c})
    write_csv(a.output/'J2_query_types.csv', ['sql_type','query_count'], [{'sql_type':t,'query_count':n} for t,n in sorted(type_counts.items())])
    dist = []
    for f, file_rows in sorted(by_file.items(), key=lambda kv: (-len(kv[1]),kv[0])):
        count = collections.Counter(r['sql_type'] for r in file_rows)
        dist.append({'file_path':f,'query_count':len(file_rows),'distinct_hotspots':len({r['start_line'] for r in file_rows}), 'select_count': count['SELECT'], 'insert_count':count['INSERT'],'update_count':count['UPDATE'],'delete_count':count['DELETE'],'other_or_unresolved':sum(v for k,v in count.items() if k not in {'SELECT','INSERT','UPDATE','DELETE'})})
    write_csv(a.output/'J2_query_distribution_by_file.csv', list(dist[0]), dist)
    write_csv(a.output/'J2_query_complexity_heuristic.csv', list(complexity_rows[0]), complexity_rows)
    smells = ET.parse(a.exports/'pandora-smells.xml').getroot().findall('./Smell')
    smell_rows = [{'kind':s.findtext('Kind',''), 'file_path':s.findtext('File','').replace('\\','/'), 'line':s.findtext('Line',''), 'certainty':s.findtext('Certainty',''), 'message':s.findtext('Message','')} for s in smells]
    write_csv(a.output/'J2_sql_smells.csv', ['kind','file_path','line','certainty','message'], smell_rows)
    complexity_counts = collections.Counter(r['heuristic_complexity'] for r in complexity_rows)
    package_count = sum(int(r['query_count']) for r in dist if '/com/pandora/dao/' in '/'+r['file_path'].replace('\\','/'))
    summary = {'inventory_queries':len(rows),'inventory_hotspots':len(hotspot_keys),'native_metrics':native,'schema_tables':tables,'schema_columns':columns,'smell_count':len(smells),'text_query_types':dict(sorted(type_counts.items())),'dynamic_placeholder_rows':dyn_count,'taa_matched_rows':taa_count,'taa_unmatched_rows':len(rows)-taa_count,'complexity_heuristic':dict(sorted(complexity_counts.items())),'queries_in_dao_package':package_count}
    (a.output/'J2_1_summary.json').write_text(json.dumps(summary,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    types_md = '\n'.join(f'| {typ} | {n} |' for typ,n in sorted(type_counts.items()))
    comp_md = '\n'.join(f'| {typ} | {n} |' for typ,n in sorted(complexity_counts.items()))
    top_files = '\n'.join(f"| `{r['file_path']}` | {r['query_count']} | {r['distinct_hotspots']} |" for r in dist[:10])
    native_line = ', '.join(f'{k}={v}' for k,v in sorted(native.items()))
    report = f'''# J2.1 — SQLInspect analysis (Plandora r348)

## Scope and tools

- Target: Plandora source-code revision r348, Java and MySQL.
- SQLInspect version: 0.4.2 (as configured in Eclipse for this analysis).
- SQL dialect: MySQL; schema definition input: `mysql.sql`.
- Post-processing: Python 3.10+ (Python standard library, no external dependencies).
- This document describes the SQLInspect-based J2.1 extraction, **not** the independent J2.2 source-code analysis.

## Reproduction

From the repository root:

```powershell
python code/scripts/generer_j2_1_csv.py --exports results/step-2/sqlinspect --output results/step-2/sqlinspect/J2_1_sqlinspect_detected_accesses.csv
python code/scripts/generer_j2_1_statistiques.py --exports results/step-2/sqlinspect --inventory results/step-2/sqlinspect/J2_1_sqlinspect_detected_accesses.csv --output results/step-2/statistics
```

The inventory is derived from `pandora-queries.xml` and cross-referenced to `pandora-taa.xml` by Java file path and execution line. Distinct hotspots are unique `(file path, execution line)` pairs. The inventory has one row per SQLInspect query entry; multiple query entries can belong to the same hotspot. The end-line field represents the JDBC call line and not necessarily the entire SQL string's source span.

## Observed results

- SQLInspect query entries: **{len(rows)}**.
- Distinct JDBC hotspot locations in the exported inventory: **{len(hotspot_keys)}**.
- SQLInspect native Java metrics (source export): **{native_line}**.
- Imported LS: **{tables} tables**, **{columns} columns**.
- SQL smells: **{len(smells)}**, including any findings whose source is `mysql.sql` rather than a Java file.
- Query entries with `{{{{...}}}}` placeholders: **{dyn_count}**.
- Query entries linked to a TAA statement by execution location: **{taa_count}**; entries without a matching TAA statement: **{len(rows)-taa_count}**. A match does not guarantee complete table/column resolution.
- Query entries whose execution file is under `com.pandora.dao`: **{package_count}** ({package_count/len(rows):.1%}).

### Query types, classified from SQL text (not native SQLInspect metrics)

| SQL text classification | Query entries |
|---|---:|
{types_md}

These counts can differ from SQLInspect's native metrics because dynamic/unresolved statements and the tool's query classification have different definitions. In particular, do **not** substitute the text-based SELECT count for the native `Selects` metric.

### Heuristic query complexity (independent post-processing)

The heuristic strips literal strings and SQLInspect placeholders, then measures explicit `JOIN`, parenthesized `SELECT`, `GROUP BY`, `HAVING`, and `UNION` signals. Score = joins + 2×subqueries + group-by + having + union. Scores 0–1 are *low*, 2–3 *moderate*, and 4+ *high*; unresolved SQL is *unclassified*. These labels are **not** native SQLInspect metrics and are **not** a complete SQL parser; comma joins, nested/dynamic fragments, and other constructs can be underestimated.

| Heuristic category | Query entries |
|---|---:|
{comp_md}

### Top 10 source files by exported query entries

| Java file | Query entries | Distinct hotspots |
|---|---:|---:|
{top_files}

The complete distributions are in the CSV files in this folder.

## Deliverables

- `../sqlinspect/pandora-queries.xml`: original detected SQL query records.
- `../sqlinspect/pandora-taa.xml`: SQLInspect table/column access analysis.
- `../sqlinspect/pandora-schema.json`: exported LS schema.
- `../sqlinspect/pandora-JavaMetrics.xml`: native Java/query metrics.
- `../sqlinspect/pandora-SQLMetrics.xml`: native SQL metrics export.
- `../sqlinspect/pandora-smells.xml`: reported SQL smells.
- `../sqlinspect/pandora.json`: additional raw SQLInspect export.
- `../sqlinspect/J2_1_sqlinspect_detected_accesses.csv`: one row per query entry, including execution location and optional TAA evidence.
- `J2_query_types.csv`, `J2_query_distribution_by_file.csv`, `J2_query_complexity_heuristic.csv`, `J2_sql_smells.csv`: reproducible post-processing statistics.
- `J2_1_summary.json`: machine-readable validation counters.

## Limitations and next step

- Query reconstruction may be incomplete for string concatenation, dynamically generated SQL, JDBC wrappers, and placeholders such as `{{{{na}}}}` / `{{{{question}}}}`.
- This data set records **SQLInspect detections**, not independently verified database execution paths.
- Unmatched TAA entries and unresolved SQL are evidence gaps, **not** proof of unused tables or columns.
- SQLInspect table/column information is only linked by execution location; where multiple statements share a location, the TAA associations are not necessarily attributable to one specific query variant.
- J2.2 must independently scan Plandora r348 Java source, inspect missed candidates, distinguish real JDBC executions from application wrappers, and cross-check SQLInspect results.
- The final logical subschema (LSS) is not established by this J2.1 report alone; it requires validated source-level evidence and schema-constraint review.
'''
    (a.output/'J2_1_SQLInspect_report.md').write_text(report,encoding='utf-8')
    print('J2.1 generated in:',a.output.resolve())
    print('Queries:',len(rows),'hotspots:',len(hotspot_keys),'native queries:',native.get('Queries'))
    print('Schema:',tables,'tables;',columns,'columns. SQL smells:',len(smells))
    print('Query text types:',dict(sorted(type_counts.items())))
    print('Generated: J2_query_types.csv, J2_query_distribution_by_file.csv, J2_query_complexity_heuristic.csv, J2_sql_smells.csv, J2_1_summary.json, J2_1_SQLInspect_report.md')
    if native.get('Queries') != len(rows) or native.get('Hotspots') != len(hotspot_keys):
        print('WARNING: native metric count differs from CSV inventory; investigate before publishing.')


if __name__ == '__main__':
    main()
